import re as _re
def _polish(x):
    """俄语排版收尾：全角分隔符→·，补空格，压缩多余空白"""
    x = x.replace("｜", " · ").replace("，", ", ")
    # 西里尔字母紧贴 ок./数字/拉丁 时补一个空格
    x = _re.sub(r"([а-яА-ЯёЁ])(ок\.)", r"\1 \2", x)
    x = _re.sub(r"([а-яА-ЯёЁ])(\d)", r"\1 \2", x)
    x = " ".join(x.split())
    return x.replace(" ,", ",").replace("( ", "(").replace(" )", ")")

